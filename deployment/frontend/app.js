function renderEvidenceDeck() {
  const uploadTray = document.getElementById("uploadTray");
  const deckContainer = document.getElementById("deckContainer");
  const physicalDeck = document.getElementById("physicalDeck");
  const threePilesStage = document.getElementById("threePilesStage");
  const analyzeBtnText = document.getElementById("analyzeBtnText");

  uploadTray.style.display = "none";
  threePilesStage.classList.remove("active");
  deckContainer.classList.add("active");

  analyzeBtnText.innerText = `ANALYZE EVIDENCE DECK (${STATE.items.length} ITEMS)`;

  // Clear previous cards except scan beam
  physicalDeck.querySelectorAll(".evidence-card").forEach(c => c.remove());

  // Render stacked cards with progressive 3D offset & slight rotation
  const maxVisualCards = Math.min(STATE.items.length, 12);
  for (let i = 0; i < maxVisualCards; i++) {
    const item = STATE.items[i];
    const card = document.createElement("div");
    card.className = "evidence-card";
    card.dataset.index = i;

    // Organic physics layering
    const rotZ = (i * 1.8 - 4.5).toFixed(1);
    const transY = (i * -2.5).toFixed(1);
    const transZ = (i * -5).toFixed(1);
    card.style.transform = `translate3d(0, ${transY}px, ${transZ}px) rotateZ(${rotZ}deg)`;
    card.style.zIndex = maxVisualCards - i;

    card.innerHTML = `
      <div class="card-gold-border"></div>
      <div class="evidence-card-photo">
        <img src="${item.url}" alt="${item.filename}">
      </div>
      <div class="card-meta-row">
        <span class="card-id-tag">${item.id || 'EVIDENCE'}</span>
        <span class="card-dim-tag">${item.dimensions || '2048 × 2048'}</span>
      </div>
    `;

    physicalDeck.appendChild(card);
  }
}

function clearEvidenceDeck() {
  STATE.items = [];
  STATE.results = [];
  document.getElementById("deckContainer").classList.remove("active");
  document.getElementById("threePilesStage").classList.remove("active");
  document.getElementById("uploadTray").style.display = "block";
}

function previewTopCard() {
  if (STATE.items.length > 0) {
    if (STATE.results.length > 0) {
      openForensicModal(STATE.results[0]);
    } else {
      openForensicModal(STATE.items[0]);
    }
  }
}

