function initDragAndDrop() {
  const tray = document.getElementById("uploadTray");
  if (!tray) return;

  ['dragenter', 'dragover'].forEach(eventName => {
    tray.addEventListener(eventName, (e) => {
      e.preventDefault();
      e.stopPropagation();
      tray.classList.add('drag-over');
    }, false);
  });

  ['dragleave', 'drop'].forEach(eventName => {
    tray.addEventListener(eventName, (e) => {
      e.preventDefault();
      e.stopPropagation();
      tray.classList.remove('drag-over');
    }, false);
  });

  tray.addEventListener('drop', (e) => {
    const dt = e.dataTransfer;
    const files = dt.files;
    if (files && files.length > 0) {
      handleFiles(Array.from(files));
    }
  });
}

function handleFileSelect(event) {
  const files = Array.from(event.target.files);
  if (files.length > 0) {
    handleFiles(files);
  }
}

function handleFiles(files) {
  STATE.items = files.map((file, idx) => ({
    id: `AF-${Math.floor(1000 + Math.random() * 9000)}`,
    file: file,
    filename: file.name,
    title: file.name,
    url: URL.createObjectURL(file),
    dimensions: "Analyzing...",
    size: `${(file.size / 1024).toFixed(1)} KB`
  }));

  renderEvidenceDeck();
}

function loadDemoSession() {
  STATE.isDemoMode = true;
  STATE.items = [...DEMO_CASES];
  renderEvidenceDeck();
}

function toggleDemoMode() {
  STATE.isDemoMode = !STATE.isDemoMode;
  const btn = document.getElementById("demoModeToggle");
  if (STATE.isDemoMode) {
    btn.style.borderColor = "var(--brass-bright)";
    loadDemoSession();
  } else {
    btn.style.borderColor = "transparent";
    clearEvidenceDeck();
  }
}

