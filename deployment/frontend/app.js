function populatePile(element, items, type) {
  element.innerHTML = "";
  if (items.length === 0) {
    element.innerHTML = `<span style="font-size: 11px; font-family: var(--font-mono); color: #64748b;">NO EVIDENCE</span>`;
    return;
  }

  // Render top cards with physical deal stacking
  const maxStack = Math.min(items.length, 5);
  for (let i = 0; i < maxStack; i++) {
    const item = items[i];
    const card = document.createElement("div");
    card.className = "evidence-card";
    card.style.position = "absolute";
    card.style.inset = "0";

    const rotZ = (i * 2 - 3).toFixed(1);
    const transY = (i * -3).toFixed(1);
    card.style.transform = `translate3d(0, ${transY}px, ${i * -4}px) rotateZ(${rotZ}deg)`;
    card.style.zIndex = maxStack - i;

    card.innerHTML = `
      <div class="card-gold-border"></div>
      <div class="evidence-card-photo">
        <img src="${item.url}" alt="${item.filename}">
      </div>
      <div class="card-meta-row">
        <span class="card-id-tag">${item.id || item.evidence_id || 'EVIDENCE'}</span>
        <span class="card-dim-tag">${item.dimensions || 'AUTHENTICATED'}</span>
      </div>
    `;

    element.appendChild(card);
  }
}

