function initCompareSlider() {
  const viewport = document.getElementById("viewportArea");
  const handle = document.getElementById("compareHandle");
  const overlay = document.getElementById("viewerOverlayImage");

  function onMove(e) {
    const rect = viewport.getBoundingClientRect();
    const x = Math.max(0, Math.min(rect.width, e.clientX - rect.left));
    const percent = (x / rect.width) * 100;
    handle.style.left = `${percent}%`;
    overlay.style.clipPath = `polygon(${percent}% 0, 100% 0, 100% 100%, ${percent}% 100%)`;
  }

  viewport.onmousemove = onMove;
}

// Procedural Forensic Canvas Renderers for High-Fidelity In-Browser Inspection
function generateSyntheticHeatmap(card) {
  const canvas = document.createElement("canvas");
  canvas.width = 400;
  canvas.height = 400;
  const ctx = canvas.getContext("2d");

  if (card.verdict === "FULL_AIGC") {
    const grad = ctx.createRadialGradient(200, 200, 20, 200, 200, 190);
    grad.addColorStop(0, "rgba(225, 29, 72, 0.85)");
    grad.addColorStop(0.7, "rgba(245, 158, 11, 0.45)");
    grad.addColorStop(1, "rgba(16, 185, 129, 0.05)");
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, 400, 400);
  } else if (card.verdict === "PARTIAL_AI") {
    ctx.fillStyle = "rgba(0,0,0,0)";
    ctx.fillRect(0, 0, 400, 400);
    ctx.beginPath();
    ctx.arc(220, 180, 75, 0, Math.PI * 2);
    ctx.fillStyle = "rgba(245, 158, 11, 0.8)";
    ctx.fill();
    ctx.lineWidth = 3;
    ctx.strokeStyle = "rgba(255, 255, 255, 0.9)";
    ctx.stroke();
  } else {
    // Authentic Clean Map
    ctx.fillStyle = "rgba(16, 185, 129, 0.12)";
    ctx.fillRect(0, 0, 400, 400);
  }
  return canvas.toDataURL();
}

function generateSyntheticSRM(card) {
  const canvas = document.createElement("canvas");
  canvas.width = 256;
  canvas.height = 256;
  const ctx = canvas.getContext("2d");
  const imgData = ctx.createImageData(256, 256);

  for (let i = 0; i < imgData.data.length; i += 4) {
    const val = card.verdict === "FULL_AIGC" 
      ? 128 + Math.sin((i / 4) * 0.4) * 60 + (Math.random() - 0.5) * 40
      : 128 + (Math.random() - 0.5) * 22;
    imgData.data[i] = val;
    imgData.data[i + 1] = val;
    imgData.data[i + 2] = val;
    imgData.data[i + 3] = 255;
  }
  ctx.putImageData(imgData, 0, 0);
  return canvas.toDataURL();
}

function generateSyntheticFFT(card) {
  const canvas = document.createElement("canvas");
  canvas.width = 256;
  canvas.height = 256;
  const ctx = canvas.getContext("2d");
  
  ctx.fillStyle = "#05070a";
  ctx.fillRect(0, 0, 256, 256);

  // Central low-frequency concentration
  const grad = ctx.createRadialGradient(128, 128, 4, 128, 128, 90);
  grad.addColorStop(0, "#ffffff");
  grad.addColorStop(0.3, "#dfba73");
  grad.addColorStop(1, "#05070a");
  ctx.fillStyle = grad;
  ctx.fillRect(0, 0, 256, 256);

  // If AIGC, draw synthetic periodic starburst harmonics
  if (card.verdict === "FULL_AIGC") {
    ctx.strokeStyle = "rgba(225, 29, 72, 0.6)";
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.moveTo(30, 30); ctx.lineTo(226, 226);
    ctx.moveTo(30, 226); ctx.lineTo(226, 30);
    ctx.stroke();
  }
  return canvas.toDataURL();
}

