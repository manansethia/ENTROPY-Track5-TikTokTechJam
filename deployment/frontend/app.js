function setViewerMode(mode) {
  STATE.activeViewerMode = mode;
  const overlay = document.getElementById("viewerOverlayImage");
  const handle = document.getElementById("compareHandle");

  document.querySelectorAll(".mode-btn").forEach(b => b.classList.remove("active"));
  
  const modeBtnMap = {
    "ORIGINAL": "btnModeOrig",
    "HEATMAP": "btnModeHeatmap",
    "SRM": "btnModeSRM",
    "FFT": "btnModeFFT",
    "COMPARE": "btnModeCompare"
  };
  if (modeBtnMap[mode]) {
    document.getElementById(modeBtnMap[mode]).classList.add("active");
  }

  handle.style.display = "none";
  overlay.style.display = "none";

  const card = STATE.selectedCard;
  if (!card) return;

  if (mode === "HEATMAP") {
    overlay.style.display = "block";
    overlay.src = generateSyntheticHeatmap(card);
  } else if (mode === "SRM") {
    overlay.style.display = "block";
    overlay.src = generateSyntheticSRM(card);
  } else if (mode === "FFT") {
    overlay.style.display = "block";
    overlay.src = generateSyntheticFFT(card);
  } else if (mode === "COMPARE") {
    overlay.style.display = "block";
    overlay.src = generateSyntheticHeatmap(card);
    handle.style.display = "block";
    initCompareSlider();
  }
}

