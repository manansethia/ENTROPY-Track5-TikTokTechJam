function exportDossier(format) {
  const card = STATE.selectedCard || DEMO_CASES[0];
  if (!card) return;

  if (format === "JSON") {
    const reportData = {
      case_id: card.id,
      timestamp: new Date().toISOString(),
      image_filename: card.filename,
      dimensions: card.dimensions,
      sha256_checksum: card.sha256,
      assessment: {
        verdict: card.verdict,
        verdict_badge: card.verdict_badge,
        ai_probability: card.probability_aigc,
        affected_area_percentage: card.affected_area,
        confidence_tier: card.confidence_tier
      },
      model: {
        name: "Triple-Hybrid Champion",
        version: "v4.3-REM-A",
        parameters: "735M (735,038,561)",
        host: "Private inference service"
      },
      spatial_forensics: {
        fft_high_freq_ratio: card.fft_high_freq,
        srm_noise_energy: card.srm_energy,
        laplacian_variance: card.lap_var,
        inconsistency_status: card.inconsistency_status
      },
      consensus_gate_weights: {
        clip_vit_l14: card.gate_clip,
        siglip_so400m: card.gate_siglip,
        srm_wavelet_trunk: card.gate_srm
      },
      provenance: {
        c2pa_status: card.c2pa,
        headline: card.provenance_headline,
        summary: card.provenance_body
      },
      camera_exif: {
        camera_model: card.camera,
        lens_model: card.lens,
        exposure: card.exposure
      }
    };

    const blob = new Blob([JSON.stringify(reportData, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `Forensic_Dossier_${card.id}.json`;
    a.click();
    showToast(`Dossier ${card.id} exported to JSON.`);
  } else if (format === "PRINT") {
    window.print();
  }
}

