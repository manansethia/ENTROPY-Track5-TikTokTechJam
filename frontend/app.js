async function applyPreviewTransform() {
  const card = STATE.selectedCard;
  if (!card?.file) {
    showToast("Transform previews are available for uploaded evidence, not the demo deck.");
    return;
  }
  const formData = new FormData();
  formData.append("file", card.file);
  formData.append("session_id", getAnalysisSessionId());
  formData.append("source_evidence_id", card.evidence_id || card.id);
  formData.append("jpeg_quality", document.getElementById("transform-quality")?.value || "85");
  formData.append("blur_radius", document.getElementById("transform-blur")?.value || "0");
  formData.append("crop_percent", document.getElementById("transform-crop")?.value || "100");
  try {
    const response = await fetch(`${STATE.apiBaseUrl}/v1/transform-preview`, { method: "POST", body: formData });
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.detail || "Transformation preview failed.");
    const transformed = toEvidenceCard(payload.transformed_result, card);
    Object.assign(card, transformed, { transformed_url: payload.image_data_url, transform_job: payload.job });
    const image = document.getElementById("workbench-img");
    if (image) image.src = card.transformed_url;
    openInspection(card);
    const delta = payload.comparison?.probability_change;
    const comparison = delta == null ? "" : ` AI probability ${delta >= 0 ? "+" : ""}${(delta * 100).toFixed(1)} pts.`;
    showToast(`TRANSFORM ${payload.job.state.toUpperCase()}: ${payload.notice}${comparison}`);
  } catch (error) {
    showToast(error.message || "Transformation preview failed.");
  }
}

