function renderArtifactCanvas(card, artifactName) {
  const canvas = document.getElementById("workbench-overlay");
  if (!canvas) return;
  canvas.width = 512;
  canvas.height = 512;
  const ctx = canvas.getContext("2d");
  const encoded = card.spatial_forensics?.artifacts?.[artifactName];
  if (!encoded) return;
  const image = new Image();
  image.onload = () => ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
  image.src = `data:image/png;base64,${encoded}`;
}

