function getAnalysisSessionId() {
  const key = "aigc-forensics-session-id";
  let sessionId = sessionStorage.getItem(key);
  if (!sessionId) {
    sessionId = `sess_${Date.now().toString(36)}_${crypto.getRandomValues(new Uint32Array(3)).join("_")}`;
    sessionStorage.setItem(key, sessionId);
  }
  return sessionId;
}

