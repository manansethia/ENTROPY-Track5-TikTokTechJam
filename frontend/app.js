  renderer.setSize(window.innerWidth, window.innerHeight);
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));

  // Lights
  const ambientLight = new THREE.AmbientLight(0xfffaed, 1.2);
  scene.add(ambientLight);

  const dirLight = new THREE.DirectionalLight(0xffe8ba, 2.0);
  dirLight.position.set(5, 8, 4);
  scene.add(dirLight);

  const rimLight = new THREE.PointLight(0xb99855, 3.5, 12);
  rimLight.position.set(-4, 3, 2);
  scene.add(rimLight);

  // Load Poly Haven PBR Materials if available
  const texLoader = new THREE.TextureLoader();
  const feltTex = texLoader.load("/assets/materials/felt-color.jpg");
  const walnutTex = texLoader.load("/assets/materials/walnut-color.jpg");

