function openInspection(item) {
  STATE.selectedCard = item;
  const modal = document.getElementById("inspection");
  if (!modal) return;
  modal.classList.add("open");

  // Populate Header
  const caseIdEl = document.getElementById("inspect-case-id");
  const filenameEl = document.getElementById("inspect-filename");
  if (caseIdEl) caseIdEl.innerText = item.id;
  if (filenameEl) filenameEl.innerText = item.filename;

  // Workbench Base Image
  const imgEl = document.getElementById("workbench-img");
  if (imgEl) imgEl.src = item.transformed_url || item.url;

  // Verdict Section
  const vTitle = document.getElementById("inspect-verdict");
  const vDesc = document.getElementById("inspect-desc");
  const vTier = document.getElementById("verdict-tier");
  const aiProb = document.getElementById("metric-ai-prob");
  const affected = document.getElementById("metric-affected");

  if (vTitle) vTitle.innerText = item.verdict_badge || item.verdict;
  if (vDesc) vDesc.innerText = item.verdict_desc || "Forensic evaluation completed.";
  if (vTier) vTier.innerText = item.confidence_tier || "HIGH CONFIDENCE";
  const pVal = Number.isFinite(item.probability_aigc) ? item.probability_aigc : (Number.isFinite(item.ai_probability) ? item.ai_probability : item.confidence);
  if (aiProb) aiProb.innerText = Number.isFinite(pVal) ? `${(pVal * 100).toFixed(1)}%` : "NOT AVAILABLE";
  if (affected) affected.innerText = item.affected_area > 0 ? `${item.affected_area}% (LOCAL)` : `0.0% (GLOBAL)`;

  // Spectral & Noise Signals (Stream C)
  const valFft = document.getElementById("val-fft");
  const barFft = document.getElementById("bar-fft");
  const valSrm = document.getElementById("val-srm");
  const barSrm = document.getElementById("bar-srm");
  const valLap = document.getElementById("val-lap");
  const barLap = document.getElementById("bar-lap");
  const valInconst = document.getElementById("val-inconst");

  if (valFft) valFft.innerText = item.fft_high_freq ?? "NOT AVAILABLE";
  if (barFft) barFft.style.setProperty("--value", `${Math.min(100, Math.max(0, Number(item.fft_high_freq || 0) * 400))}%`);
  if (valSrm) valSrm.innerText = item.srm_energy ?? "NOT AVAILABLE";
  if (barSrm) barSrm.style.setProperty("--value", `${Math.min(100, Math.max(0, Number(item.srm_energy || 0) * 12))}%`);
  if (valLap) valLap.innerText = item.lap_var ?? "NOT AVAILABLE";
  if (barLap) barLap.style.setProperty("--value", `${Math.min(100, Math.max(0, Number(item.lap_var || 0) / 8))}%`);
  if (valInconst) {
    valInconst.innerText = item.inconsistency_status || "NOT AVAILABLE";
    valInconst.style.color = item.inconsistency_status === "ANOMALY_DETECTED" ? "var(--amber)" : "var(--emerald)";
  }

  // Model Consensus Gate Weights
  const valClip = document.getElementById("val-clip");
  const barClip = document.getElementById("bar-clip");
  const valSiglip = document.getElementById("val-siglip");
  const barSiglip = document.getElementById("bar-siglip");
  const valSrmGate = document.getElementById("val-srm-gate");
  const barSrmGate = document.getElementById("bar-srm-gate");

  if (valClip) valClip.innerText = "NOT EXPOSED";
  if (barClip) barClip.style.setProperty("--value", "0%");
  if (valSiglip) valSiglip.innerText = "NOT EXPOSED";
  if (barSiglip) barSiglip.style.setProperty("--value", "0%");
  if (valSrmGate) valSrmGate.innerText = "NOT EXPOSED";
  if (barSrmGate) barSrmGate.style.setProperty("--value", "0%");

  // Hardware & EXIF
  const metaCam = document.getElementById("meta-camera");
  const metaLens = document.getElementById("meta-lens");
  const metaExp = document.getElementById("meta-exp");
  const metaDim = document.getElementById("meta-dim");
  const metaC2pa = document.getElementById("meta-c2pa");
  const metaSha = document.getElementById("meta-sha");

  if (metaCam) metaCam.innerText = item.camera || "NOT PRESENT (STRIPPED)";
  if (metaLens) metaLens.innerText = item.lens || "N/A";
  if (metaExp) metaExp.innerText = item.exposure || "N/A";
  if (metaDim) metaDim.innerText = item.dimensions || "2048 × 2048";
  if (metaC2pa) metaC2pa.innerText = item.c2pa || "NOT DETECTED";
  if (metaSha) metaSha.innerText = item.sha256 ? `${item.sha256.substring(0, 16)}...` : "NOT AVAILABLE";

  // Provenance Stamp Text
  const provHead = document.getElementById("prov-headline");
  const provBody = document.getElementById("prov-body");
  if (provHead) provHead.innerText = item.provenance_headline || "NO VERIFIED PROVENANCE";
  if (provBody) provBody.innerText = item.provenance_body || "No provenance statement was detected.";

  const heatmap = item.spatial_forensics?.artifacts?.heatmap_overlay_base64;
  const heatmapField = document.getElementById("workbench-heatmap");
  if (heatmapField) heatmapField.style.backgroundImage = heatmap ? `url("data:image/png;base64,${heatmap}")` : "none";

  // Set default view mode
  setWorkbenchMode("HEAT");
}

function cycleInspection(direction) {
  const ordered = STATE.results.length ? STATE.results : STATE.items;
  if (!STATE.selectedCard || ordered.length < 2) return;
  const index = ordered.findIndex(item => item.id === STATE.selectedCard.id);
  const next = ordered[(index + direction + ordered.length) % ordered.length];
  if (next) openInspection(next);
}

