function renderEvidenceDeck() {
  const deck = document.getElementById("evidence-deck");
  const headline = document.getElementById("tray-headline");
  const sessionCount = document.getElementById("session-count");
  const classifiedDecks = document.getElementById("classified-decks");
  const experience = document.getElementById("experience");

  if (classifiedDecks) classifiedDecks.style.display = "none";
  if (experience) experience.classList.remove("has-results");

  if (headline) headline.innerText = `${STATE.items.length} EXHIBITS STAGED`;
  if (sessionCount) sessionCount.innerText = `${STATE.items.length} ITEMS READY`;

  if (!deck) return;
  deck.innerHTML = "";

  // Keep a controlled, selectable window for larger batches. The full physical
  // stack is implied by depth while every visible card remains a usable target.
  const displayCount = Math.min(STATE.items.length, window.innerWidth <= 620 ? 4 : 5);
  const maxOffset = Math.max(0, STATE.items.length - displayCount);
  STATE.deckOffset = Math.min(STATE.deckOffset, maxOffset);
  const visibleItems = STATE.items.slice(STATE.deckOffset, STATE.deckOffset + displayCount);
  if (!visibleItems.some((item) => item.id === STATE.stagedCardId)) {
    STATE.stagedCardId = visibleItems[0]?.id || null;
  }

  for (let i = 0; i < displayCount; i++) {
    const item = visibleItems[i];
    const card = document.createElement("button");
    card.className = "evidence-card";
    card.dataset.id = item.id;
    card.setAttribute("aria-label", `Select exhibit ${item.id}: ${item.filename}`);
    card.setAttribute("aria-pressed", String(item.id === STATE.stagedCardId));
    if (item.id === STATE.stagedCardId) card.classList.add("is-selected");
    card.onclick = () => selectStagedCard(item.id);
    card.ondblclick = () => openInspection(item);

    // Preserve a compact physical deck; the classified piles use this same
    // dense stacking language after the deal.
    const x = (i * 3 - (displayCount - 1) * 1.5).toFixed(1);
    const y = (i * -2.5).toFixed(1);
    const z = (i * -3).toFixed(1);
    const r = (i * 1.1 - (displayCount - 1) * .55).toFixed(1);

    card.style.setProperty("--x", `${x}px`);
    card.style.setProperty("--y", `${y}px`);
    card.style.setProperty("--z", `${z}px`);
    card.style.setProperty("--r", `${r}deg`);
    card.style.zIndex = displayCount - i;

    const sealNum = (i + 1).toString().padStart(2, '0');

    card.innerHTML = `
      <div class="card-shell">
        <img class="card-photo" src="${item.url}" alt="${item.filename}">
        <div class="card-seal">${sealNum}</div>
        <div class="card-meta">
          <div>
            <strong>${item.id}</strong>
            <small title="${item.filename}">${compactFileName(item.filename).toUpperCase()}</small>
          </div>
          <span>${item.dimensions || '2048 × 2048'}</span>
        </div>
      </div>
    `;

    deck.appendChild(card);
  }

  deck.onwheel = (event) => {
    if (STATE.items.length <= displayCount) return;
    event.preventDefault();
    const nextOffset = Math.max(0, Math.min(maxOffset, STATE.deckOffset + (event.deltaY > 0 ? 1 : -1)));
    if (nextOffset !== STATE.deckOffset) {
      STATE.deckOffset = nextOffset;
      renderEvidenceDeck();
    }
  };

  deck.querySelectorAll(".evidence-card").forEach((card, hoveredIndex) => {
    card.addEventListener("pointerenter", () => {
      deck.querySelectorAll(".evidence-card").forEach((other, index) => {
        const direction = Math.sign(index - hoveredIndex);
        other.style.setProperty("--hover-shift", index === hoveredIndex ? "0px" : `${direction * Math.max(7, 22 - Math.abs(index - hoveredIndex) * 4)}px`);
      });
    });
    card.addEventListener("pointerleave", () => {
      deck.querySelectorAll(".evidence-card").forEach((other) => other.style.setProperty("--hover-shift", "0px"));
    });
  });
}

