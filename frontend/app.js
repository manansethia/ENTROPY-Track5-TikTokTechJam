function compactFileName(filename, maxLength = 24) {
  if (!filename || filename.length <= maxLength) return filename || "UNTITLED IMAGE";
  const extensionIndex = filename.lastIndexOf(".");
  const extension = extensionIndex > 0 ? filename.slice(extensionIndex) : "";
  const stem = extension ? filename.slice(0, extensionIndex) : filename;
  const room = Math.max(6, maxLength - extension.length - 4);
  const head = Math.ceil(room * .58);
  const tail = Math.floor(room * .42);
  return `${stem.slice(0, head)}....${stem.slice(-tail)}${extension}`;
}

